// Generates backend/src/countries.h from the mledoze/countries dataset.
//
//   curl -L -o countries.json https://raw.githubusercontent.com/mledoze/countries/5.1.0/countries.json
//   node tools/make-seed.mjs countries.json > backend/src/countries.h
//
// The data is compiled into the server and inserted with prepared
// statements, so the server never executes SQL text read from disk.
//
// Dataset: https://github.com/mledoze/countries (ODbL-1.0)
import { readFileSync } from 'node:fs'

const src = process.argv[2]
if (!src) {
  console.error('usage: node tools/make-seed.mjs <countries.json>')
  process.exit(1)
}

const data = JSON.parse(readFileSync(src, 'utf8'))

// C string literal. Escapes backslash, quote and control chars; UTF-8
// bytes pass through as-is (gcc/clang read sources as UTF-8).
const str = (v) =>
  '"' +
  String(v ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/[\x00-\x1f\x7f]/g, (c) => `\\x${c.charCodeAt(0).toString(16).padStart(2, '0')}""`) +
  '"'
const num = (v) => (Number.isFinite(v) ? String(v) : '0')
const list = (obj) => Object.values(obj ?? {}).join(', ')

const rows = data
  .filter((c) => c.independent && /^[A-Z]{2}$/.test(c.cca2))
  .sort((a, b) => a.name.common.localeCompare(b.name.common))
  .map(
    (c) =>
      `    {${[
        str(c.cca2.toLowerCase()),
        str(c.name.common),
        str((c.capital ?? []).join(', ')),
        str(c.region),
        str(c.subregion),
        num(c.area),
        str(list(c.languages)),
        str(Object.values(c.currencies ?? {}).map((x) => x.name).join(', ')),
        c.landlocked ? 1 : 0,
        (c.borders ?? []).length,
      ].join(', ')}},`
  )

const out = [
  '// Generated by tools/make-seed.mjs from mledoze/countries 5.1.0 (ODbL-1.0).',
  '// Do not edit by hand.',
  '#ifndef COUNTRIES_H',
  '#define COUNTRIES_H',
  '',
  'struct seed_country {',
  '  const char *code, *name, *capital, *region, *subregion;',
  '  double area;',
  '  const char *languages, *currencies;',
  '  int landlocked, borders;',
  '};',
  '',
  'static const struct seed_country SEED_COUNTRIES[] = {',
  ...rows,
  '};',
  '',
  '#endif',
  '',
]
process.stdout.write(out.join('\n'))
console.error(`wrote ${rows.length} countries`)
