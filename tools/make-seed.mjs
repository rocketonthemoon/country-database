// Generates backend/data/seed.sql from the mledoze/countries dataset.
//
//   curl -L -o countries.json https://raw.githubusercontent.com/mledoze/countries/5.1.0/countries.json
//   node tools/make-seed.mjs countries.json > backend/data/seed.sql
//
// Dataset: https://github.com/mledoze/countries (ODbL-1.0)
import { readFileSync } from "node:fs";

const src = process.argv[2];
if (!src) {
  console.error("usage: node tools/make-seed.mjs <countries.json>");
  process.exit(1);
}

const data = JSON.parse(readFileSync(src, "utf8"));

const q = (v) =>
  v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`;
const num = (v) => (Number.isFinite(v) ? String(v) : "NULL");
const list = (obj) => Object.values(obj ?? {}).join(", ");

const rows = data
  .filter((c) => c.independent && /^[A-Z]{2}$/.test(c.cca2))
  .sort((a, b) => a.name.common.localeCompare(b.name.common))
  .map((c) =>
    [
      q(c.cca2.toLowerCase()),
      q(c.name.common),
      q((c.capital ?? []).join(", ")),
      q(c.region),
      q(c.subregion),
      num(c.area),
      q(list(c.languages)),
      q(Object.values(c.currencies ?? {}).map((x) => x.name).join(", ")),
      c.landlocked ? 1 : 0,
      (c.borders ?? []).length,
    ].join(", ")
  );

const out = [
  "-- Generated by tools/make-seed.mjs from mledoze/countries 5.1.0 (ODbL-1.0). Do not edit by hand.",
  "BEGIN;",
  ...rows.map(
    (r) =>
      `INSERT INTO countries (code, name, capital, region, subregion, area, languages, currencies, landlocked, borders) VALUES (${r});`
  ),
  "COMMIT;",
  "",
];
process.stdout.write(out.join("\n"));
console.error(`wrote ${rows.length} countries`);
